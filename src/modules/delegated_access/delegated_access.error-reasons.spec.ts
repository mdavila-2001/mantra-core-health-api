describe('DelegatedAccessErrorReason (gobierno de accesos)', () => {
  it.each(CONTRACT_CODES)('%s existe y sale con %i', (code, status) => {
    expect((Reason as Record<string, string>)[code]).toBe(code);
    expect(
      DELEGATED_ACCESS_GOVERNANCE_STATUS[code as keyof typeof Reason],
    ).toBe(status);
  });

  it.each(INTERNAL_CODES)('el código interno %s existe con estado', (code) => {
    expect((Reason as Record<string, string>)[code]).toBe(code);
    expect(
      DELEGATED_ACCESS_GOVERNANCE_STATUS[code as keyof typeof Reason],
    ).toBeGreaterThanOrEqual(400);
  });

  it('el valor de cada razón es su propio nombre (estable para el cliente)', () => {
    for (const [key, value] of Object.entries(Reason)) {
      expect(value).toBe(key);
    }
  });
});
