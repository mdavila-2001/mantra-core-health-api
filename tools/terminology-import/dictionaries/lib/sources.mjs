// =============================================================================
// Registro de las fuentes de los diccionarios médicos generales (todo lo que
// no son enfermedades, síntomas, alergias, análisis, servicios, medicamentos ni
// enfermería, que cargan sus propias sesiones).
//
// Cada fuente fija:
//  - QUÉ archivo se baja: URL a una etiqueta de release o a un commit (nunca a
//    `master`), así dos corridas leen lo mismo.
//  - Su licencia, tal como la declara el registro de OBO Foundry
//    (registry/ontologies.jsonld) o el propio repositorio.
//  - `load`: 'default' si sirve a una consulta concreta del producto (dicha en
//    `productQuery`), 'opt-in' si sólo se construye y queda como fuente
//    descargable (se carga con `--include <id>`). Lección del corpus MeSH de
//    1,44 M de filas que se retiró porque nadie lo consultaba.
//  - `idPrefixes`: sólo se toman los términos propios. Los OBO traen
//    importados de otras ontologías (cl.obo trae 7 688 términos GO y 5 062 de
//    Uberon): esos se cargan desde su propia fuente, no dos veces.
//
// Las URL son de raw.githubusercontent.com / storage.googleapis.com porque son
// donde cada proyecto publica sus releases y porque son los hosts que deja
// pasar la red de la sesión que armó esto (purl.obolibrary.org, www.ebi.ac.uk,
// *.nlm.nih.gov y query.wikidata.org estaban bloqueados; ver SOURCES.md).
// =============================================================================

